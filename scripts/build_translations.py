def localize_attrs(attrs: dict[str, str]) -> dict[str, dict[str, dict[str, str]]]:
    """Build per-language {key: value} dicts, translating known keys/values and passing
    numeric/unit tokens through unchanged."""
    out = {lang: {} for lang in LANGS}
    for key, value in attrs.items():
        key_tr = ATTR_KEYS.get(key)
        # option family keys may be missing from the dictionary; fall back to the key itself
        key_tr = key_tr or (key, key, key)
        val_tr = ATTR_VALUES.get(value)
        val_tr = val_tr or (value, value, value)
        for i, lang in enumerate(LANGS):
            out[lang][key_tr[i]] = val_tr[i]
    return out


def build() -> None:
    catalog = json.loads(
        (ROOT / "examples" / "retail" / "data" / "catalog.json").read_text(encoding="utf-8")
    )
    by_id = {p["product_id"]: p for p in catalog["products"]}
    result: dict[str, dict] = {}

    for pid, (title_tr, short_tr) in P.items():
        product = by_id[pid]
        entry: dict[str, dict] = {}
        for i, lang in enumerate(LANGS):
            short = short_tr[i]
            loc = {
                "title": title_tr[i],
                "short_description": short,
                "long_description": short + SUFFIX[lang],
                "attributes": localize_attrs(product.get("attributes", {})),
            }
            # localize_attrs returns {lang: {...}}; pick this language
            loc["attributes"] = loc["attributes"][lang]
            entry[lang] = loc
        result[pid] = entry

    missing = set(by_id) - set(result)
    assert not missing, f"products missing translation: {sorted(missing)}"
    assert len(result) == 50, f"expected 50, got {len(result)}"
    (DATA / "translations.json").write_text(
        json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(f"wrote translations.json for {len(result)} products")


if __name__ == "__main__":
    build()
